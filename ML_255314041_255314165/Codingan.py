def jalankan_analisis_kartu_kredit():
    print("\n" + "=" * 70)
    print("MEMULAI ANALISIS BAGIAN B: DATASET KARTU KREDIT (TANTANGAN)")
    print("=" * 70)

    cfg = KONFIG["kredit"]
    out_dir = "output_kredit"
    os.makedirs(out_dir, exist_ok=True)

    if not os.path.exists(cfg["file"]):
        print(f"File {cfg['file']} tidak ditemukan! Analisis Bagian B dilewati.")
        return

    df_kredit = pd.read_csv(cfg["file"])
    print(f"Ukuran data mentah kartu kredit: {df_kredit.shape}")

    # Cleaning data
    df_kredit = df_kredit.dropna(subset=["CREDIT_LIMIT"]).reset_index(drop=True)
    df_kredit["MINIMUM_PAYMENTS"] = df_kredit["MINIMUM_PAYMENTS"].fillna(
        df_kredit["MINIMUM_PAYMENTS"].median()
    )
    df_kredit["CASH_ADVANCE_FREQUENCY"] = df_kredit[
        "CASH_ADVANCE_FREQUENCY"
    ].clip(upper=1)

    fitur_k = [c for c in df_kredit.columns if c != cfg["id_col"]]
    Xk_df = df_kredit[fitur_k].copy()
    for c in cfg["log_cols"]:
        Xk_df[c] = np.log1p(Xk_df[c])

    X_kredit = StandardScaler().fit_transform(Xk_df)

    # K-Means k=4
    km_k = KMeans(n_clusters=4, n_init=10, random_state=RANDOM_STATE).fit(
        X_kredit
    )
    df_kredit["cluster"] = km_k.labels_

    # Evaluasi Internal (Soal B.1)
    sil_k = silhouette_score(
        X_kredit[:SIL_SAMPLE], km_k.labels_[:SIL_SAMPLE], random_state=RANDOM_STATE
    )
    dbi_k = davies_bouldin_score(X_kredit, km_k.labels_)
    print("\n=== EVALUASI METRIK INTERNAL KARTU KREDIT (k=4) ===")
    print(f"Silhouette Score (Sample 3000): {sil_k:.3f}")
    print(f"Davies-Bouldin Index (DBI)     : {dbi_k:.3f}")

    # Profil Median Persona (Soal B.2)
    fitur_profil = [
        "BALANCE",
        "BALANCE_FREQUENCY",
        "PURCHASES",
        "ONEOFF_PURCHASES",
        "INSTALLMENTS_PURCHASES",
        "CASH_ADVANCE",
        "PURCHASES_FREQUENCY",
        "CASH_ADVANCE_FREQUENCY",
        "CASH_ADVANCE_TRX",
        "CREDIT_LIMIT",
        "PAYMENTS",
    ]
    med_kredit = df_kredit.groupby("cluster")[fitur_profil].median().round(2).T
    persona_nama = {
        0: "Nasabah Pasif (1.571)",
        1: "Pengguna Tarik Tunai (2.764)",
        2: "Pembelanja Aktif Bernilai Tinggi (2.572)",
        3: "Pembelanja Cicilan (2.042)",
    }
    med_kredit.columns = [persona_nama[i] for i in med_kredit.columns]

    print("\n=== PROFIL MEDIAN PERSONA NASABAH KARTU KREDIT (SOAL B.2) ===")
    print(med_kredit.to_string())

    print("\n=== DISTRIBUSI JUMLAH NASABAH PER PERSONA ===")
    print(df_kredit["cluster"].value_counts().sort_index())


# =============================================================================
# TITIK EKSEKUSI PROGRAM
