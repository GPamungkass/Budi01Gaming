import os
import time
import warnings
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from scipy.cluster.hierarchy import dendrogram, linkage
from sklearn.cluster import DBSCAN, AgglomerativeClustering, KMeans
from sklearn.decomposition import PCA
from sklearn.metrics import (
    adjusted_rand_score,
    davies_bouldin_score,
    silhouette_score,
)
from sklearn.neighbors import NearestNeighbors
from sklearn.preprocessing import StandardScaler

warnings.filterwarnings("ignore")
sns.set_theme(style="whitegrid")

# =============================================================================
# 0. KONFIGURASI UMUM
# =============================================================================
RANDOM_STATE = 42
SIL_SAMPLE = 3000  # Sampel untuk kalkulasi silhouette agar efisien
rng = np.random.RandomState(RANDOM_STATE)

KONFIG = {
    "bean": dict(
        file="dataset_dry_bean.csv", label="Class", id_col=None, log_cols=[]
    ),
    "kredit": dict(
        file="dataset_kartu_kredit.csv",
        label=None,
        id_col="CUST_ID",
        log_cols=[
            "BALANCE",
            "PURCHASES",
            "ONEOFF_PURCHASES",
            "INSTALLMENTS_PURCHASES",
            "CASH_ADVANCE",
            "CASH_ADVANCE_TRX",
            "PURCHASES_TRX",
            "CREDIT_LIMIT",
            "PAYMENTS",
            "MINIMUM_PAYMENTS",
        ],
    ),
}


def simpan(fig, nama, out_dir):
    """Simpan gambar ke folder output lalu tampilkan."""
    os.makedirs(out_dir, exist_ok=True)
    fig.savefig(os.path.join(out_dir, nama), dpi=150, bbox_inches="tight")
    plt.show()


def sil(X, label):
    """Silhouette pada sampel acak; titik noise DBSCAN (-1) diabaikan."""
    label = np.asarray(label)
    m = label != -1
    if len(np.unique(label[m])) < 2:
        return np.nan
    idx = np.where(m)[0]
    if len(idx) > SIL_SAMPLE:
        idx = rng.choice(idx, SIL_SAMPLE, replace=False)
    return silhouette_score(X[idx], label[idx])


# =============================================================================
# BAGIAN A: DATASET DRY BEAN (WAJIB)
# =============================================================================
def jalankan_analisis_dry_bean():
    print("=" * 70)
    print("MEMULAI ANALISIS BAGIAN A: DATASET DRY BEAN")
    print("=" * 70)

    cfg = KONFIG["bean"]
    out_dir = "output_bean"
    os.makedirs(out_dir, exist_ok=True)

    # 1. Memuat Data
    df = pd.read_csv(cfg["file"])
    print(f"Ukuran data awal: {df.shape}")
    print("\nDistribusi label asli:")
    print(df[cfg["label"]].value_counts())

    # 2. Cleaning (Soal A.1)
    print(
        f"\nMissing value per kolom:\n{df.isna().sum()[df.isna().sum() > 0]}"
    )
    jumlah_duplikat = df.duplicated().sum()
    print(f"Jumlah baris duplikat yang dibuang: {jumlah_duplikat}")
    df = df.drop_duplicates().reset_index(drop=True)

    y = df[cfg["label"]]
    fitur = [c for c in df.columns if c != cfg["label"]]
    print(
        f"Ukuran setelah cleaning: {df.shape} | Jumlah fitur prediktor: {len(fitur)}"
    )

    # 3. Eksplorasi Distribusi & Korelasi
    n = len(fitur)
    ncol = 6
    fig, axes = plt.subplots(
        int(np.ceil(n / ncol)), ncol, figsize=(18, 2.6 * np.ceil(n / ncol))
    )
    for a, f in zip(axes.ravel(), fitur):
        sns.histplot(df[f], ax=a, bins=40, color="#5b9bd5")
        a.set_title(f, fontsize=8)
        a.set_xlabel("")
        a.set_ylabel("")
    for a in axes.ravel()[n:]:
        a.axis("off")
    fig.tight_layout()
    simpan(fig, "01_distribusi_fitur.png", out_dir)

    fig, ax = plt.subplots(figsize=(11, 9))
    sns.heatmap(
        df[fitur].corr(),
        cmap="RdBu_r",
        center=0,
        annot=True,
        fmt=".1f",
        annot_kws={"size": 7},
        ax=ax,
    )
    ax.set_title("Korelasi Antarfitur")
    simpan(fig, "02_korelasi.png", out_dir)

    kor = (
        df[fitur]
        .corr()
        .abs()
        .where(np.triu(np.ones((n, n)), 1).astype(bool))
        .stack()
    )
    print(
        f"\nPasangan fitur dengan |korelasi| > 0,9 : {int((kor > 0.9).sum())}"
    )
    print(kor[kor > 0.9].sort_values(ascending=False).head(10).round(3))

    # 4. Standarisasi dan PCA
    X = StandardScaler().fit_transform(df[fitur])

    pca_full = PCA(random_state=RANDOM_STATE).fit(X)
    kum = np.cumsum(pca_full.explained_variance_ratio_)
    fig, ax = plt.subplots(figsize=(8, 3.8))
    ax.bar(
        range(1, n + 1),
        pca_full.explained_variance_ratio_,
        color="#9dc3e6",
        label="per komponen",
    )
    ax.plot(range(1, n + 1), kum, "o-", color="#c00000", label="kumulatif")
    ax.axhline(0.9, ls="--", color="grey")
    ax.set(
        xlabel="Komponen utama",
        ylabel="Proporsi varians",
        title="Scree plot PCA",
    )
    ax.legend()
    simpan(fig, "03_pca_scree.png", out_dir)
    print(
        f"\nJumlah komponen untuk mencapai 90% varians: {int(np.argmax(kum > 0.9) + 1)}"
    )

    P2 = PCA(n_components=2, random_state=RANDOM_STATE).fit_transform(X)
    fig, ax = plt.subplots(figsize=(8, 6))
    sns.scatterplot(
        x=P2[:, 0],
        y=P2[:, 1],
        hue=y,
        s=6,
        linewidth=0,
        palette="tab10",
        ax=ax,
    )
    ax.set(
        title="Label Asli pada Bidang PCA (Bukan Input Clustering)",
        xlabel="PC1",
        ylabel="PC2",
    )
    ax.legend(markerscale=3, fontsize=8)
    simpan(fig, "04_label_asli_pca.png", out_dir)

    # 5. K-Means (k = 2 s.d. 10) (Soal A.2)
    print("\n--- Menghitung Metrik K-Means (k=2 s.d. 10) ---")
    hasil_k = []
    for k in range(2, 11):
        km_ = KMeans(n_clusters=k, n_init=10, random_state=RANDOM_STATE).fit(X)
        baris = {
            "k": k,
            "inertia": km_.inertia_,
            "silhouette": sil(X, km_.labels_),
            "davies_bouldin": davies_bouldin_score(X, km_.labels_),
            "ARI_vs_label": adjusted_rand_score(y, km_.labels_),
        }
        hasil_k.append(baris)

    eval_k = pd.DataFrame(hasil_k)
    print(eval_k.round(3).to_string(index=False))

    fig, ax = plt.subplots(1, 3, figsize=(15, 3.8))
    ax[0].plot(eval_k.k, eval_k.inertia, "o-")
    ax[0].set(title="Elbow (WCSS)", xlabel="k")
    ax[1].plot(eval_k.k, eval_k.silhouette, "o-", color="#c55a11")
    ax[1].set(title="Silhouette (sampel)", xlabel="k")
    ax[2].plot(eval_k.k, eval_k.ARI_vs_label, "o-", color="#548235")
    ax[2].set(title="ARI terhadap label asli", xlabel="k")
    fig.tight_layout()
    simpan(fig, "05_kmeans_pemilihan_k.png", out_dir)

    # Model K-Means Final k=7
    t0 = time.time()
    km = KMeans(n_clusters=7, n_init=10, random_state=RANDOM_STATE).fit(X)
    waktu_km = time.time() - t0
    lab_km = km.labels_
    print(
        f"\nK-Means k=7 selesai dalam {waktu_km:.3f} detik. Ukuran klaster: {np.bincount(lab_km)}"
    )

    # Eksperimen Tambahan Soal A.3 (Pamungkas)
    pca4 = PCA(n_components=4, random_state=RANDOM_STATE)
    X_pca4 = pca4.fit_transform(X)
    km_pca4 = KMeans(n_clusters=7, n_init=10, random_state=RANDOM_STATE).fit(
        X_pca4
    )

    fitur_subset = [
        "Area",
        "AspectRation",
        "Extent",
        "Solidity",
        "roundness",
        "ShapeFactor4",
    ]
    X_subset = StandardScaler().fit_transform(df[fitur_subset])
    km_subset = KMeans(n_clusters=7, n_init=10, random_state=RANDOM_STATE).fit(
        X_subset
    )

    tabel_a3 = pd.DataFrame(
        [
            {
                "Input": "16 Fitur Penuh",
                "Dimensi": 16,
                "DBI": round(davies_bouldin_score(X, lab_km), 3),
                "ARI": round(adjusted_rand_score(y, lab_km), 3),
            },
            {
                "Input": "PCA 4 Komponen",
                "Dimensi": 4,
                "DBI": round(davies_bouldin_score(X_pca4, km_pca4.labels_), 3),
                "ARI": round(adjusted_rand_score(y, km_pca4.labels_), 3),
            },
            {
                "Input": "Subset 6 Fitur Non-Redundan",
                "Dimensi": 6,
                "DBI": round(
                    davies_bouldin_score(X_subset, km_subset.labels_), 3
                ),
                "ARI": round(adjusted_rand_score(y, km_subset.labels_), 3),
            },
        ]
    )
    print("\n=== PERBANDINGAN K-MEANS REDUKSI DIMENSI (SOAL A.3) ===")
    print(tabel_a3.to_string(index=False))

    # 6. Hierarchical Clustering (Agglomerative) (Soal A.4)
    print("\n--- Menjalankan Hierarchical Clustering (Linkage Analysis) ---")
    idx_d = rng.choice(len(X), 2000, replace=False)
    Z = linkage(X[idx_d], method="ward")
    fig, ax = plt.subplots(figsize=(13, 4.5))
    dendrogram(
        Z, truncate_mode="lastp", p=40, ax=ax, color_threshold=Z[-(7 - 1), 2]
    )
    ax.set(
        title="Dendrogram Ward (Sampel 2.000 Titik); Garis Warna = Potongan 7 Klaster",
        xlabel="Kelompok titik (ukuran dalam kurung)",
        ylabel="Jarak penggabungan",
    )
    simpan(fig, "06_dendrogram.png", out_dir)

    banding_linkage = []
    lab_hier = {}
    for link in ["ward", "complete", "average"]:
        t0 = time.time()
        lab = AgglomerativeClustering(n_clusters=7, linkage=link).fit_predict(X)
        dt = time.time() - t0
        lab_hier[link] = lab
        baris = {
            "linkage": link,
            "waktu_detik": round(dt, 1),
            "silhouette": sil(X, lab),
            "ukuran_klaster": sorted(np.bincount(lab).tolist(), reverse=True),
            "ARI_vs_label": round(adjusted_rand_score(y, lab), 3),
        }
        banding_linkage.append(baris)

    print("\n=== PERBANDINGAN LINKAGE HIERARCHICAL (SOAL A.4) ===")
    print(pd.DataFrame(banding_linkage).to_string(index=False))

    # 7. DBSCAN (Soal A.5)
    print("\n--- Menjalankan Grid Search DBSCAN ---")
    MS_PCA, MS_FULL = 40, 2 * n
    kdist_plot(
        P2, MS_PCA, "k-distance (2 komponen PCA)", "07_kdist_pca2.png", out_dir
    )
    kdist_plot(
        X, MS_FULL, f"k-distance (seluruh {n} fitur)", "08_kdist_full.png", out_dir
    )

    grid = []
    for ruang, Xd, ms, eps_list in [
        ("PCA-2D", P2, MS_PCA, [0.15, 0.20, 0.25, 0.30, 0.40]),
        (f"{n} fitur", X, MS_FULL, [0.80, 1.00, 1.50, 2.00, 2.50]),
    ]:
        for eps in eps_list:
            lab = DBSCAN(eps=eps, min_samples=ms).fit_predict(Xd)
            baris = {
                "ruang": ruang,
                "eps": eps,
                "min_samples": ms,
                "n_klaster": len(set(lab)) - (1 if -1 in lab else 0),
                "noise_%": round((lab == -1).mean() * 100, 1),
                "ARI_vs_label": round(adjusted_rand_score(y, lab), 3),
            }
            grid.append(baris)

    grid_df = pd.DataFrame(grid)
    print("\n=== HASIL GRID SEARCH DBSCAN (SOAL A.5) ===")
    print(grid_df.to_string(index=False))

    t0 = time.time()
    lab_db = DBSCAN(eps=0.30, min_samples=MS_PCA).fit_predict(P2)
    waktu_db = time.time() - t0

    # 8. Perbandingan Ketiga Algoritma (Soal A.7)
    semua = {
        "K-Means": (lab_km, waktu_km),
        "Hierarchical (Ward)": (
            lab_hier["ward"],
            banding_linkage[0]["waktu_detik"],
        ),
        "DBSCAN": (lab_db, waktu_db),
    }

    ringkas = []
    for nama, (lab, durasi) in semua.items():
        m = lab != -1
        baris = {
            "algoritma": nama,
            "n_klaster": len(set(lab[m])),
            "noise_%": round((~m).mean() * 100, 1),
            "silhouette": round(sil(X, lab), 3),
            "davies_bouldin": (
                round(davies_bouldin_score(X[m], lab[m]), 3)
                if len(set(lab[m])) > 1
                else np.nan
            ),
            "waktu_detik": round(durasi, 1),
            "ARI_vs_label": round(adjusted_rand_score(y, lab), 3),
        }
        ringkas.append(baris)

    ringkas_df = pd.DataFrame(ringkas)
    print("\n=== PERBANDINGAN TIGA ALGORITMA (SOAL A.7) ===")
    print(ringkas_df.to_string(index=False))
    print(
        f"\nKesamaan K-Means vs Ward (ARI): {round(adjusted_rand_score(lab_km, lab_hier['ward']), 3)}"
    )

    panel = [
        ("Label asli", y),
        ("K-Means", lab_km),
        ("Hierarchical (Ward)", lab_hier["ward"]),
        ("DBSCAN", lab_db),
    ]
    fig, axes = plt.subplots(1, len(panel), figsize=(5.2 * len(panel), 4.6))
    for a, (judul, lab) in zip(axes, panel):
        lab_arr = np.asarray(lab).astype(str)
        lab_arr = np.where(lab_arr == "-1", "noise", lab_arr)
        urut = sorted(set(lab_arr), key=lambda s: (s == "noise", s))
        pal = dict(
            zip([u for u in urut if u != "noise"], sns.color_palette("tab10", 10))
        )
        pal["noise"] = (0.8, 0.8, 0.8)
        sns.scatterplot(
            x=P2[:, 0],
            y=P2[:, 1],
            hue=lab_arr,
            hue_order=urut,
            palette=pal,
            s=4,
            linewidth=0,
            ax=a,
            legend=False,
        )
        a.set(title=judul, xlabel="PC1", ylabel="PC2")
    fig.tight_layout()
    simpan(fig, "09_perbandingan_pca.png", out_dir)

    # 9. Validasi Eksternal: Tabel Silang & Purity
    tab = pd.crosstab(
        y, lab_km, rownames=["Varietas asli"], colnames=["Klaster K-Means"]
    )
    fig, ax = plt.subplots(figsize=(8, 5))
    sns.heatmap(tab, annot=True, fmt="d", cmap="Blues", ax=ax)
    ax.set_title("Tabel Silang Varietas Asli vs Klaster K-Means")
    simpan(fig, "10_tabel_silang.png", out_dir)

    purity = tab.max(axis=0).sum() / tab.values.sum()
    print(f"\nPurity K-Means: {purity:.3f}")

    # 10. Profil Klaster & Penamaan (Soal A.6)
    df["cluster"] = lab_km
    fitur_geo = [
        "Area",
        "Perimeter",
        "MajorAxisLength",
        "MinorAxisLength",
        "AspectRation",
        "roundness",
        "Compactness",
        "Solidity",
    ]
    med_bean = df.groupby("cluster")[fitur_geo].median().round(3)

    nama_klaster = {
        0: "Kecil kompak (DERMASON 92%)",
        1: "Besar lonjong, kurang cembung (CALI 50%)",
        2: "Ramping memanjang (HOROZ 94%)",
        3: "Raksasa (BOMBAY 100%)",
        4: "Besar proporsional (CALI 53%)",
        5: "Bulat (SEKER 92%)",
        6: "Sedang agak lonjong (SIRA 75%)",
    }
    med_bean["Nama Klaster"] = med_bean.index.map(nama_klaster)
    med_bean["Jumlah Titik"] = df["cluster"].value_counts().sort_index()

    print("\n=== PROFIL DAN PENAMAAN KLASTER K-MEANS (SOAL A.6) ===")
    print(
        med_bean[
            [
                "Nama Klaster",
                "Jumlah Titik",
                "Area",
                "AspectRation",
                "roundness",
                "Compactness",
            ]
        ].to_string()
    )


def kdist_plot(Xd, ms, judul, nama, out_dir):
    d = np.sort(
        NearestNeighbors(n_neighbors=ms).fit(Xd).kneighbors(Xd)[0][:, -1]
    )
    fig, ax = plt.subplots(figsize=(7, 3.5))
    ax.plot(d)
    for q in (90, 95):
        ax.axhline(np.percentile(d, q), ls="--", color="grey")
        ax.text(5, np.percentile(d, q), f"persentil {q}", fontsize=8, va="bottom")
    ax.set(title=judul, xlabel="Titik (diurutkan)", ylabel=f"jarak ke tetangga ke-{ms}")
    simpan(fig, nama, out_dir)


